// The unbundled Electron launcher uses the same Lucide artwork as React controls.
const fs = require('node:fs');
const path = require('node:path');
const React = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
const Lucide = require('lucide-react');
const root = path.resolve(__dirname, '../..');
const constants = fs.readFileSync(path.join(root, 'src/shared/iconMetrics.ts'), 'utf8');
const size = Number(constants.match(/inline: (\d+)/)[1]);
const strokeWidth = Number(constants.match(/ICON_STROKE = ([\d.]+)/)[1]);
const names = { terminal: 'Terminal', cloud: 'Cloud', refresh: 'RefreshCw', settings: 'Settings', gear: 'Settings', play: 'Play', arrow: 'ArrowUpRight', copy: 'Copy', cloudPlus: 'CloudUpload', monitor: 'Monitor', phone: 'Smartphone', x: 'X', logOut: 'LogOut' };
const icons = Object.fromEntries(Object.entries(names).map(([key, name]) => [key, renderToStaticMarkup(React.createElement(Lucide[name], { size, strokeWidth, 'aria-hidden': true }))]));
const target = path.join(root, 'electron/launcher/lucide-icons.js');
const output = '// Generated by scripts/release/generate-launcher-icons.cjs\nwindow.DROVER_ICONS = ' + JSON.stringify(icons, null, 2) + ';\n';
// Preserve checkout line endings and avoid marking a clean release tree dirty.
if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== output) {
  fs.writeFileSync(target, output);
}
